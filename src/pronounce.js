/* =============================================================================
   pronounce.js — turns a Francis-Smith spelling into an easy "say it like" guide
   e.g.  Wela'lin → "weh-LAH-leen"   Mu'in → "MOO-een"   Kwe' → "KWEH"
   CAPITAL syllables = hold that vowel longer (it has an apostrophe after it).
   This is an approximate guide generated by rules, not a recording.
   ============================================================================= */
const VOWELS = { a: 'ah', e: 'eh', i: 'ee', o: 'oh', u: 'oo', 'ɨ': 'uh' };
const isV = (c) => c in VOWELS;

function segment(word) {
  const w = word.toLowerCase().replace(/[’‘`]/g, "'").replace(/[^a-zɨ'\s-]/g, '');
  const segs = [];
  for (let i = 0; i < w.length; i++) {
    const c = w[i];
    if (c === ' ' || c === '-') { segs.push({ t: 'gap' }); continue; }
    if (c === "'") {
      const prev = segs[segs.length - 1];
      if (prev && prev.t === 'v') prev.long = true;          // a' = long vowel
      else if (prev && prev.t === 'c') segs.push({ t: 'v', ch: 'ɨ', long: false }); // l'mu'j = short "uh"
      continue;
    }
    const prev = segs[segs.length - 1];
    if (c === 'w' && prev && prev.t === 'c' && (prev.ch === 'k' || prev.ch === 'q')) { prev.ch += 'w'; continue; } // kw / qw stay together
    segs.push(isV(c) ? { t: 'v', ch: c, long: false } : { t: 'c', ch: c });
  }
  return segs;
}

function consonant(segs, i) {
  const c = segs[i].ch;
  const prev = segs[i - 1], next = segs[i + 1];
  const between = prev && prev.t === 'v' && next && next.t === 'v';
  const final = !next || next.t === 'gap';
  switch (c) {
    case 'p': return between ? 'b' : 'p';
    case 't': return between ? 'd' : 't';
    case 'k': return between ? 'g' : 'k';
    case 's': return between ? 'z' : 's';
    case 'j': return final ? 'ch' : 'j';
    case 'q': return final ? 'kh' : 'k';
    case 'kw': return between ? 'gw' : 'kw';
    case 'qw': return 'kw';
    default: return c;
  }
}

function pronounceWord(segs) {
  // Each vowel takes the consonant just before it as the start of its syllable
  // (or the whole cluster at the start of the word); extra consonants close the previous syllable.
  const out = []; let units = []; let last = null;
  segs.forEach((s, i) => {
    if (s.t === 'v') {
      let onset = units;
      if (last && units.length > 1) { last.text += units.slice(0, -1).join(''); onset = units.slice(-1); }
      last = { text: onset.join('') + VOWELS[s.ch], long: s.long };
      out.push(last); units = [];
    } else units.push(consonant(segs, i));
  });
  if (units.length) { if (last) last.text += units.join(''); else out.push({ text: units.join(''), long: false }); }
  return out.map((x) => (x.long ? x.text.toUpperCase() : x.text)).join('-');
}

export function pronounce(text) {
  if (!text) return '';
  const words = segment(text);
  const groups = []; let g = [];
  words.forEach((s) => { if (s.t === 'gap') { if (g.length) groups.push(g); g = []; } else g.push(s); });
  if (g.length) groups.push(g);
  return groups.map(pronounceWord).join('  ');
}
